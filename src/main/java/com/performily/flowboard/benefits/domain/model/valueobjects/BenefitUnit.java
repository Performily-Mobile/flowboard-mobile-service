package com.performily.flowboard.benefits.domain.model.valueobjects;

/**
 * Benefit Unit
 * @summary
 * Unit in which the quantity of a benefit type is measured.
 * MONEY is expressed in soles (PEN), DAYS in calendar days and UNITS in whole items.
 *
 * @since 1.0.0
 */
public enum BenefitUnit {
    MONEY,
    DAYS,
    UNITS
}
